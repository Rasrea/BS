def is_synonym(a: str, b: str) -> bool:
    """判断两个材质/空间名是否为同义词"""
    if not a or not b:
        return False
    a, b = a.strip().lower(), b.strip().lower()
    if a == b:
        return True
    for group in SYNONYM_GROUPS:
        lower_group = {x.lower() for x in group}
        if a in lower_group and b in lower_group:
            return True
    return False
